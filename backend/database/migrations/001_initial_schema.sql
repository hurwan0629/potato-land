CREATE TABLE chat_rooms (
  idx BIGINT GENERATED BY DEFAULT AS IDENTITY,
  listing_idx BIGINT NOT NULL,
  buyer_idx BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_message_at TIMESTAMPTZ,

  CONSTRAINT pk_chat_rooms PRIMARY KEY (idx),
  CONSTRAINT fk_chat_rooms_listing
    FOREIGN KEY (listing_idx) REFERENCES listings (idx),
  CONSTRAINT fk_chat_rooms_buyer
    FOREIGN KEY (buyer_idx) REFERENCES users (idx),
  CONSTRAINT uq_chat_rooms_listing_buyer UNIQUE (listing_idx, buyer_idx)
);

CREATE INDEX idx_chat_rooms_buyer_recent
  ON chat_rooms (buyer_idx, last_message_at DESC);

CREATE TABLE transactions (
  idx BIGINT GENERATED BY DEFAULT AS IDENTITY,
  listing_idx BIGINT NOT NULL,
  seller_idx BIGINT NOT NULL,
  buyer_idx BIGINT NOT NULL,
  transaction_type transaction_type NOT NULL,
  status transaction_status NOT NULL DEFAULT 'REQUESTED',
  amount BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ,
  canceled_by BIGINT,

  CONSTRAINT pk_transactions PRIMARY KEY (idx),
  CONSTRAINT fk_transactions_listing
    FOREIGN KEY (listing_idx) REFERENCES listings (idx),
  CONSTRAINT fk_transactions_seller
    FOREIGN KEY (seller_idx) REFERENCES users (idx),
  CONSTRAINT fk_transactions_buyer
    FOREIGN KEY (buyer_idx) REFERENCES users (idx),
  CONSTRAINT fk_transactions_canceled_by
    FOREIGN KEY (canceled_by) REFERENCES users (idx),
  CONSTRAINT chk_transactions_amount CHECK (amount >= 0),
  CONSTRAINT chk_transactions_participants CHECK (seller_idx <> buyer_idx)
);

CREATE INDEX idx_transactions_listing
  ON transactions (listing_idx);

CREATE INDEX idx_transactions_buyer
  ON transactions (buyer_idx);

CREATE INDEX idx_transactions_seller
  ON transactions (seller_idx);

CREATE UNIQUE INDEX uq_transactions_listing_active_or_completed
  ON transactions (listing_idx)
  WHERE status IN ('REQUESTED', 'COMPLETED');

CREATE TABLE chat_messages (
  idx BIGINT GENERATED BY DEFAULT AS IDENTITY,
  chat_room_idx BIGINT NOT NULL,
  sender_idx BIGINT,
  client_message_id VARCHAR(100),
  message_type chat_message_type NOT NULL,
  transaction_idx BIGINT,
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT pk_chat_messages PRIMARY KEY (idx),
  CONSTRAINT fk_chat_messages_room
    FOREIGN KEY (chat_room_idx) REFERENCES chat_rooms (idx),
  CONSTRAINT fk_chat_messages_sender
    FOREIGN KEY (sender_idx) REFERENCES users (idx),
  CONSTRAINT fk_chat_messages_transaction
    FOREIGN KEY (transaction_idx) REFERENCES transactions (idx),
  CONSTRAINT uq_chat_messages_client_message
    UNIQUE (chat_room_idx, sender_idx, client_message_id),
  CONSTRAINT chk_chat_messages_sender_by_type CHECK (
    (message_type IN ('SYSTEM', 'TRADE_COMPLETE') AND sender_idx IS NULL)
    OR
    (message_type IN ('TEXT', 'IMAGE', 'PAYMENT_REQUEST') AND sender_idx IS NOT NULL)
  ),
  CONSTRAINT chk_chat_messages_client_message_id CHECK (
    message_type <> 'TEXT' OR client_message_id IS NOT NULL
  )
);

CREATE INDEX idx_chat_messages_room_recent
  ON chat_messages (chat_room_idx, created_at DESC, idx DESC);

CREATE TABLE reviews (
  idx BIGINT GENERATED BY DEFAULT AS IDENTITY,
  transaction_idx BIGINT NOT NULL,
  reviewer_idx BIGINT NOT NULL,
  reviewee_idx BIGINT NOT NULL,
  rating SMALLINT NOT NULL,
  content TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT pk_reviews PRIMARY KEY (idx),
  CONSTRAINT fk_reviews_transaction
    FOREIGN KEY (transaction_idx) REFERENCES transactions (idx),
  CONSTRAINT fk_reviews_reviewer
    FOREIGN KEY (reviewer_idx) REFERENCES users (idx),
  CONSTRAINT fk_reviews_reviewee
    FOREIGN KEY (reviewee_idx) REFERENCES users (idx),
  CONSTRAINT uq_reviews_transaction_reviewer
    UNIQUE (transaction_idx, reviewer_idx),
  CONSTRAINT chk_reviews_rating CHECK (rating BETWEEN 1 AND 10),
  CONSTRAINT chk_reviews_content_length
    CHECK (content IS NULL OR CHAR_LENGTH(content) <= 50),
  CONSTRAINT chk_reviews_participants CHECK (reviewer_idx <> reviewee_idx)
);

CREATE INDEX idx_reviews_reviewee
  ON reviews (reviewee_idx);
